        }

        private const string Readme = """
# LE3 cutscene corpus

Generated by Legendary Explorer (Asset Database > Cutscene Corpus). It describes how BioWare staged every
conversation in the game: the script, the branching, every track on every node's matinee, the BioStage cameras and
actor slots in the main level packages, and each camera cut measured against the actors. It is meant to be read by
an agent that is directing a new cutscene: find similar real nodes, copy their measured shots and timings, and
retarget them.

Every file is JSON Lines (one JSON object per line) except `manifest.json`, `camera_presets_game.json`, and the
`scripts/` text files. Load into SQLite with `python build_sqlite.py` (standard library only) if you want SQL.

## Files

| File | One line per | Key fields |
|---|---|---|
| `conversations.jsonl` | BioConversation | `id`, `name`, `file`, `speakers`, `startNodes`, `stageDirections`, `chosenStageContextId` |
| `nodes.jsonl` | conversation node | `conversationId`, `id` (E#/R#), `speaker`, `listener`, `text`, `stageDirection`, `cameraIntimacy`, `replyType`, `replies`/`next`, `timeline`, `shots` |
| `conversation_stages.jsonl` | StartConversation + linked BioStage | `conversationName`, `stageId`, `links`, `actors` (world origins) |
| `stages.jsonl` | placed BioStage | `origin`, `bones` (camera/node/puppet bones, world + stage-local), `cameras` (tag, world, local, fov, DOF settings) |
| `camera_moves.jsonl` | moving matinee camera in a node | `localKeys` relative to the subject actor, `move`, `size`, `lineText` |
| `animations.jsonl` | AnimSequence in a scanned package | `set`, `sequence`, `length`, `frames` |
| `level_cameras.jsonl` | placed CameraActor in a main package | `tag`, `origin`, `fov` |
| `camera_presets_game.json` | — | every moving camera as an Interp Editor saved TrackMove preset; import it from the Camera Preset dialog |
| `scripts/<conversationId>.txt` | conversation | human-readable screenplay with shots, gestures and links, in branch order |
| `manifest.json`, `errors.log` | — | counts, settings, per-file problems |

Ids: conversations are `"{package stem}:{conversation name}"`; nodes are `E{index}` (NPC entry) and `R{index}`
(player reply) within a conversation; stages are `"{package}#{uindex}"`.

## Branching

Entry nodes list the replies offered after them in `replies` (`target`, `paraphrase`, `category` = wheel slot).
Reply nodes list the entries they lead to in `next`. `startNodes` on the conversation are the possible first lines.
Speakers: index -2 is the player, -1 the owner, 0..n index `speakers`. A listener index of -3 is the default
listener; `listener` resolves it to Owner for player replies and Player for NPC lines. The Owner's real tag is in
`conversation_stages.links.Owner`.

## Timelines

`timeline.tracks` holds every track on the node's InterpData. Each track has `group`, `actor`, `class`, `kind`,
`settings` (non-key properties) and `keys` (each key has `t` in seconds plus its data, with the original Unreal
property names). Kinds: `gesture`, `camera_move`, `actor_move`, `fov`, `director`, `stage_camera`, `lookat`,
`facing`, `dof`, `lighting`, `vo`, `facefx`, `faceonly_vo`, `prop`, `interrupt`, `anim`, `sound`, `event`, `fade`,
`visibility`, `float_prop`, `other`.

- `timeline.cuts`: director cuts (time, target InterpGroup).
- `timeline.stageCameraSwitches`: BioEvtSysTrackSwitchCamera keys (time, BioStage camera tag).
- Gesture keys carry `gestureAnimLength` when the animation was found in `animations.jsonl`.
- Move keys: `pos` world [x,y,z], `rot` [roll, pitch, yaw] degrees, tangents and `interp`.

## Shots (measured)

`shots` on a node splits it at each cut. The director track decides who owns the view: a cut to a group with a
TrackMove is a `matinee` camera; a cut to the group holding the SwitchCamera track (usually "Conversation") hands
the view to the BioStage cameras, which then follow the switch keys (`stage`); a cut to a group bound to a placed
CameraActor is `level`. Without a director, the stage switch keys alone drive the cuts. A node with no cut keeps the
previous node's camera. `unresolved` means the director targets a group that does not exist in that node. For each shot:

- `source` `stage`, `matinee`, `level` or `unresolved`; `camera` is the stage camera tag or the group name.
- `subject`: the actor nearest frame centre whose face is visible; a nearer actor seen from behind or much nearer
  becomes `overShoulderOf`. `subjectRole` is speaker, listener or other. `inFrame` lists every actor inside the frame.
  When no actor is in frame (inserts, environment shots, or an actor position we could not resolve) `subject` is
  absent and `nearestActor`/`nearestActorAngle` say who was closest to the view direction.
- `subjectPositionSource`: `node_track` (the node's own actor TrackMove), `previous_node` (where an earlier node in the
  flow left the actor), or `stage_slot` (the StartConversation slot on the BioStage). Stage-camera shots always use
  stage slots or the node's own tracks.
- `distance` (cm, camera to subject eyes), `frameHeight` (cm of frame height at the subject),
  `size` from frameHeight: ECU < 40, CU < 75, MCU < 115, MS < 170, MWS < 250, FS < 400, WS otherwise.
- `azimuth`: 0 = in front of the subject's face, +90 = the subject's left, -90 = their right, 180 = behind.
- `angle`: eye_level / high / low from the camera's elevation over the subject's eyes; `heightAboveEyes`, `pitch`.
- `lineSide`: camera side of the speaker->listener line. `linePair` + `lineSideCanonical` use the alphabetically
  sorted pair, so 180-degree-rule continuity can be compared between nodes regardless of who speaks.
- `localPosition` [forward, right, up] cm and `localRotation` [roll, pitch, yaw] relative to the subject's actor
  origin: the same convention as Interp Editor camera presets. Copy these to reproduce a shot on new actors.
- `move` labels (push_in, pull_out, arc_left/right, crane_up/down, truck, pan_left/right, tilt_up/down,
  zoom_in/out, static) with numeric `moveDelta`.

## Stages

A BioStage is a level actor whose skeletal mesh bones are camera positions (`cam*`) and actor marks (`Node*`,
`Pup*`). StartConversation actions in the main (non-localized) package link the conversation, the stage and the
actors (`links`: Owner, Player, Node0..N, Stage). `conversation_stages.actors` gives resolved actor origins by tag,
slot and Owner/Player. A conversation can be started from several places; `stageContextIds` lists all candidates and
`chosenStageContextId` the one used for shots (most referenced stage cameras found, then the main package).
Bone `local` coordinates are relative to the stage origin, so a stage's camera layout can be reused elsewhere.

## Known approximations

- Eye height is pawn origin + 75 cm (stage slots are lifted 88 cm from the floor to pawn origin); sizes are binned
  from frame height and are approximate. Sitting or crouching actors read slightly wide.
- Camera and actor curves are evaluated linearly between keys (tangents are kept in the data, not used for measuring).
- FOV defaults to 70 when a camera has no FOV track, stage FOV or CameraActor FOV (`fovSource` = default).
- Actor positions carried between nodes follow the first path that reaches a node from the start nodes; other
  branches may leave actors elsewhere.
- BioEvtSysTrackSetFacing (stage node + orientation) and TrackMoves with MoveFrame other than IMF_World are kept in
  the tracks but not applied to measurements.
- Shots are only measured when actor positions are known (stage context or actor TrackMoves).

## Recipes

- Find shots BioWare used for short angry NPC lines: filter `nodes.jsonl` on `stageDirection`/`text`, then read
  their `shots` (`size`, `azimuth`, `localPosition`).
- Check 180-degree continuity: walk `replies`/`next` and compare `lineSideCanonical` for the same `linePair`.
- Reuse a camera move: take a `camera_moves.jsonl` record (or import `camera_presets_game.json`) and apply it with
  the Interp Editor camera preset tools using your subject actor as the origin.
""";

        private const string SqliteScript = """
#!/usr/bin/env python3
# Builds cutscene_corpus.sqlite from the JSONL files in this folder. Standard library only.
# Each table keeps the full record in a `json` column (query it with json_extract) plus a few indexed columns.
import json, os, sqlite3, sys

here = os.path.dirname(os.path.abspath(__file__))
db_path = os.path.join(here, "cutscene_corpus.sqlite")
if os.path.exists(db_path):
    os.remove(db_path)
db = sqlite3.connect(db_path)

def rows(name):
    path = os.path.join(here, name)
    if not os.path.exists(path):
        return
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                yield json.loads(line)

db.executescript('''
CREATE TABLE conversations(id TEXT PRIMARY KEY, name TEXT, file TEXT, dlc TEXT, is_mod INT, stage_context TEXT, json TEXT);
CREATE TABLE nodes(conversation_id TEXT, id TEXT, kind TEXT, speaker TEXT, listener TEXT, text TEXT,
                   stage_direction TEXT, camera_intimacy INT, reply_type TEXT, length REAL, json TEXT,
                   PRIMARY KEY(conversation_id, id));
CREATE TABLE shots(conversation_id TEXT, node_id TEXT, idx INT, start REAL, end REAL, source TEXT, camera TEXT,
                   subject TEXT, subject_role TEXT, size TEXT, azimuth REAL, distance REAL, fov REAL,
                   line_side TEXT, move TEXT, json TEXT);
CREATE TABLE stages(id TEXT PRIMARY KEY, file TEXT, tag TEXT, json TEXT);
CREATE TABLE conversation_stages(id TEXT PRIMARY KEY, conversation_name TEXT, file TEXT, stage_id TEXT, json TEXT);
CREATE TABLE camera_moves(id TEXT PRIMARY KEY, conversation_id TEXT, node_id TEXT, subject_role TEXT, size TEXT, move TEXT, json TEXT);
CREATE TABLE animations(set_name TEXT, sequence TEXT, length REAL, frames INT, json TEXT);
''')

for c in rows("conversations.jsonl"):
    db.execute("INSERT OR REPLACE INTO conversations VALUES (?,?,?,?,?,?,?)",
               (c["id"], c.get("name"), c.get("file"), c.get("dlc"), int(c.get("isMod", False)), c.get("chosenStageContextId"), json.dumps(c)))
for n in rows("nodes.jsonl"):
    shots = n.get("shots") or []
    db.execute("INSERT OR REPLACE INTO nodes VALUES (?,?,?,?,?,?,?,?,?,?,?)",
               (n["conversationId"], n["id"], n.get("kind"), n.get("speaker"), n.get("listener"), n.get("text"),
                n.get("stageDirection"), n.get("cameraIntimacy"), n.get("replyType"),
                (n.get("timeline") or {}).get("length"), json.dumps(n)))
    for i, s in enumerate(shots):
        db.execute("INSERT INTO shots VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                   (n["conversationId"], n["id"], i, s.get("start"), s.get("end"), s.get("source"), s.get("camera"),
                    s.get("subject"), s.get("subjectRole"), s.get("size"), s.get("azimuth"), s.get("distance"),
                    s.get("fov"), s.get("lineSide"), "+".join(s.get("move") or []), json.dumps(s)))
for s in rows("stages.jsonl"):
    db.execute("INSERT OR REPLACE INTO stages VALUES (?,?,?,?)", (s["id"], s.get("file"), s.get("tag"), json.dumps(s)))
for s in rows("conversation_stages.jsonl"):
    db.execute("INSERT OR REPLACE INTO conversation_stages VALUES (?,?,?,?,?)",
               (s["id"], s.get("conversationName"), s.get("file"), s.get("stageId"), json.dumps(s)))
for m in rows("camera_moves.jsonl"):
    db.execute("INSERT OR REPLACE INTO camera_moves VALUES (?,?,?,?,?,?,?)",
               (m["id"], m.get("conversationId"), m.get("nodeId"), m.get("subjectRole"), m.get("size"), "+".join(m.get("move") or []), json.dumps(m)))
for a in rows("animations.jsonl"):
    db.execute("INSERT INTO animations VALUES (?,?,?,?,?)", (a.get("set"), a.get("sequence"), a.get("length"), a.get("frames"), json.dumps(a)))

db.executescript('''
CREATE INDEX nodes_speaker ON nodes(speaker);
CREATE INDEX shots_size ON shots(size, subject_role);
CREATE INDEX shots_node ON shots(conversation_id, node_id);
CREATE INDEX conversation_stages_name ON conversation_stages(conversation_name);
''')
db.commit()
print("wrote", db_path)
""";
    }
}
